    def _sc(self, score):
        if score is None: return '#7f8c8d'
        if score >= 60: return '#1b5e20'
        if score >= 30: return '#2e7d32'
        if score >= 10: return '#66bb6a'
        if score >= -10: return '#757575'
        if score >= -30: return '#ef6c00'
        if score >= -60: return '#e64a19'
        return '#c62828'

    def _sbg(self, score):
        if score is None: return '#f5f5f5'
        if score >= 40: return '#e8f5e9'
        if score >= 20: return '#f1f8e9'
        if score >= -20: return '#f5f5f5'
        if score >= -40: return '#fff3e0'
        return '#ffebee'

    def _sbar(self, name, score, label, color):
        if score is None or not isinstance(score, (int, float)):
            left = 50; width = 0
            score_str = 'N/A'
            label = label or 'Insufficient Data'
            color = '#7f8c8d'
        else:
            pos = (score + 100) / 2
            if score >= 0:
                left = 50; width = pos - 50
            else:
                left = pos; width = 50 - pos
            score_str = str(score)
        h = '<div class="sbar-c"><div class="sbar-l"><span class="nm">' + name + '</span>'
        h += '<span class="vl" style="color:' + color + '">' + score_str + ' &bull; ' + label + '</span></div>'
        h += '<div class="sbar"><div class="sbar-m"></div>'
        h += '<div class="sbar-f" style="left:' + str(left) + '%;width:' + str(width) + '%;background:' + color + '"></div></div></div>'
        return h

