    def _clean_llm_markdown(self, text):
        """Sanitizes raw LLM markdown into safe HTML or strips it."""
        if not text:
            return ""
        text = re.sub(r'^###\s*(.*)$', r'<h4 style="margin:12px 0 4px 0;color:#2c3e50;">\1</h4>', text, flags=re.MULTILINE)
        text = re.sub(r'\*\*(.*?)\*\*', r'<strong>\1</strong>', text)
        text = re.sub(r'(?<!\*)\*(?!\*)(.*?)(?<!\*)\*(?!\*)', r'<em>\1</em>', text)
        text = text.replace('###', '').replace('**', '')
        text = text.replace('\n', '<br>')
        return text

