    @staticmethod
    def _fmt_cap(v):
        if not v:
            return 'N/A'
        try:
            v = float(v)
        except Exception:
            return 'N/A'
        for div, suf in [(1e12, 'T'), (1e9, 'B'), (1e6, 'M')]:
            if v >= div:
                return f'{v/div:,.1f}{suf}'
        return f'{v:,.0f}'

    def _corr_color(self, val):
        try:
            val = max(-1.0, min(1.0, float(val)))
        except Exception:
            return '#f5f5f5', '#333'
        if val >= 0:
            t = val
            r = int(255 + (27 - 255) * t); g = int(255 + (94 - 255) * t); b = int(255 + (32 - 255) * t)
        else:
            t = -val
            r = int(255 + (183 - 255) * t); g = int(255 + (28 - 255) * t); b = int(255 + (28 - 255) * t)
        bg = f'#{r:02x}{g:02x}{b:02x}'
        txt = '#ffffff' if abs(val) > 0.6 else '#1a1a1a'
        return bg, txt

